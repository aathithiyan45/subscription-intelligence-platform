-- =====================================================================
-- SubSense Subscription Intelligence Platform - Initial Schema (V1)
-- =====================================================================

-- 1. Users table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);

-- 2. Subscriptions table
CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_cycle VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITHOUT TIME ZONE,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    status VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT subscriptions_billing_cycle_check CHECK (billing_cycle IN ('WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY')),
    CONSTRAINT subscriptions_category_check CHECK (category IN ('ENTERTAINMENT', 'SOFTWARE', 'UTILITIES', 'FITNESS', 'WORK', 'EDUCATION', 'OTHER')),
    CONSTRAINT subscriptions_status_check CHECK (status IN ('ACTIVE', 'PAUSED', 'CANCELLED', 'EXPIRED'))
);

CREATE INDEX IF NOT EXISTS idx_subscription_user_status ON subscriptions (user_id, status);

-- 3. Price Histories table
CREATE TABLE IF NOT EXISTS price_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    effective_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    subscription_id BIGINT NOT NULL,
    CONSTRAINT fk_price_histories_subscription FOREIGN KEY (subscription_id) REFERENCES subscriptions(id)
);

CREATE INDEX IF NOT EXISTS idx_price_history_subscription_effective_date ON price_histories (subscription_id, effective_date);

-- 4. Notification Logs table
CREATE TABLE IF NOT EXISTS notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    error_message VARCHAR(1000),
    last_attempt_at TIMESTAMP(6) WITHOUT TIME ZONE,
    max_retries INTEGER NOT NULL DEFAULT 3,
    notification_type VARCHAR(50) NOT NULL,
    renewal_date DATE NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    sent_at TIMESTAMP(6) WITHOUT TIME ZONE,
    status VARCHAR(30) NOT NULL,
    subscription_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_notification_log_sub_date_type UNIQUE (subscription_id, renewal_date, notification_type),
    CONSTRAINT fk_notification_logs_subscription FOREIGN KEY (subscription_id) REFERENCES subscriptions(id),
    CONSTRAINT fk_notification_logs_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT notification_logs_notification_type_check CHECK (notification_type IN ('RENEWAL_REMINDER', 'PRICE_HIKE_ALERT')),
    CONSTRAINT notification_logs_status_check CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);
